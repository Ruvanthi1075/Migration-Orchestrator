# ----------------------------------------------------------------------
# Validation / planning (pure Python - no Mininet needed)
# ----------------------------------------------------------------------

def plan_topology(spec):
    """Validate `spec`; return a dict with the normalized plan plus 'cyclic'."""
    sw, hosts, links = spec['switches'], spec['hosts'], [tuple(l) for l in spec['links']]
    if len(sw) < 2:
        raise ValueError('need at least 2 switches')
    seen = {}
    for name, dpid in sw.items():
        d = str(dpid).lower()
        if len(d) != 16 or any(c not in '0123456789abcdef' for c in d):
            raise ValueError('%s: dpid %r must be 16 hex chars' % (name, dpid))
        if int(d, 16) == 0:
            raise ValueError('%s: dpid must be non-zero (OVS treats all-zero as unset)' % name)
        if d in seen:
            raise ValueError('dpid %s used by both %s and %s' % (d, seen[d], name))
        seen[d] = name
    for h, s in hosts.items():
        if s not in sw:
            raise ValueError('host %s attached to unknown switch %s' % (h, s))
    norm = set()
    for a, b in links:
        if a not in sw or b not in sw:
            raise ValueError('link (%s, %s) references an unknown switch' % (a, b))
        if a == b:
            raise ValueError('self-link on %s' % a)
        key = frozenset((a, b))
        if key in norm:
            raise ValueError('duplicate link (%s, %s)' % (a, b))
        norm.add(key)
    # connectivity via union-find
    parent = {n: n for n in sw}

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x
    for a, b in links:
        parent[find(a)] = find(b)
    if len({find(n) for n in sw}) != 1:
        raise ValueError('switch graph is not connected')
    return {'switches': dict(sw), 'hosts': dict(hosts), 'links': links,
            'cyclic': len(links) > len(sw) - 1}


def host_ip(index, total):
    """h1 -> 10.0.0.11/24 (original scheme); switches to a /16 when there are many hosts."""
    n = index + 10
    if total + 10 < 250:
        return '10.0.0.%d/24' % n
    return '10.0.%d.%d/16' % (n // 250, n % 250 + 1)


# ----------------------------------------------------------------------
# Mininet side
# ----------------------------------------------------------------------

def enable_stp(switch):
    """Force STP on via ovs-vsctl (the stp=True kwarg is not reliable on all builds)."""
    switch.cmd(f'ovs-vsctl set bridge {switch.name} stp_enable=true')


def configure_switch_ssl(switch):
    """Point one switch's OpenFlow control channel at the controller over SSL."""
    switch.cmd(f'ovs-vsctl set-ssl {SWITCH_KEY} {SWITCH_CERT} {CA_CERT}')
    switch.cmd(
        f'ovs-vsctl set-controller {switch.name} '
        f'ssl:{CONTROLLER_IP}:{CONTROLLER_PORT}'
    )


def run_sync():
    """Regenerate flows_config.json, docs/PORTS.md, port registry and Hybrid certs."""
    from mininet.log import info, warn
    if os.environ.get('QSMO_AUTO_SYNC', '1') == '0':
        info('*** QSMO_AUTO_SYNC=0 -> skipping sync_topology.sh (run it by hand)\n')
        return
    info('*** Syncing flows / ports / Hybrid certs to this topology (sync_topology.sh)\n')
    try:
        subprocess.run(['bash', SYNC_SCRIPT], check=True, timeout=600)
    except Exception as exc:  # never block the testbed on a sync problem
        warn('*** sync_topology.sh failed (%s). Run it manually before migrating.\n' % exc)


def build(spec=None):
    from mininet.net import Mininet
    from mininet.node import RemoteController, OVSKernelSwitch
    from mininet.cli import CLI
    from mininet.link import TCLink
    from mininet.log import info

    plan = plan_topology(spec or TOPOLOGY)
    cyclic = plan['cyclic']
    names = list(plan['switches'])

    net = Mininet(controller=RemoteController, switch=OVSKernelSwitch,
                  link=TCLink, autoSetMacs=True)

    info('*** Adding controller (external os-ken process, SSL, started separately)\n')
    net.addController('c0', controller=RemoteController,
                      ip=CONTROLLER_IP, port=CONTROLLER_PORT)

    info('*** Adding %d switches (STP %s)\n' % (len(names), 'ON - topology has a loop' if cyclic else 'off - loop-free'))
    switches = {}
    for name, dpid in plan['switches'].items():
        switches[name] = net.addSwitch(name, cls=OVSKernelSwitch, protocols='OpenFlow13',
                                       stp=cyclic, dpid=dpid)

    info('*** Adding %d hosts\n' % len(plan['hosts']))
    total = len(plan['hosts'])
    hosts = {}
    for i, h in enumerate(plan['hosts'], start=1):
        hosts[h] = net.addHost(h, ip=host_ip(i, total))

    info('*** Wiring hosts to switches\n')
    for h, s in plan['hosts'].items():
        net.addLink(hosts[h], switches[s])

    info('*** Wiring %d switch-to-switch links\n' % len(plan['links']))
    for a, b in plan['links']:
        net.addLink(switches[a], switches[b])

    info('*** Starting network\n')
    net.start()

    if cyclic:
        info('*** Force-enabling STP via ovs-vsctl\n')
        for name in names:
            enable_stp(switches[name])

    # Flip every switch to ssl: immediately, before any waiting, to keep the
    # window where switches retry plaintext against an SSL listener short.
    info('*** Configuring per-switch SSL control channel (%d switches)\n' % len(names))
    for name in names:
        configure_switch_ssl(switches[name])

    run_sync()

    if cyclic:
        info('*** Waiting for STP to converge (%ds)...\n' % STP_WAIT_S)
        time.sleep(STP_WAIT_S)
        info('*** Verify: sudo ovs-appctl stp/show <switch>  (ports forwarding, not blocking)\n')
    else:
        time.sleep(3)
    info('*** Verify with: sudo ovs-vsctl show   (is_connected: true on Controller lines)\n')
    info('*** Ready. Try: pingall\n')
    CLI(net)
    net.stop()


def main(argv=None):
    ap = argparse.ArgumentParser(description='Launch the QSMO Mininet testbed.')
    ap.add_argument('--topology', help='default | line:N | ring:N | star:N | mesh:N | tree:DEPTH:FANOUT')
    ap.add_argument('--check', action='store_true', help='validate the topology and exit (no Mininet)')
    args = ap.parse_args(argv)
    spec = from_name(args.topology) if args.topology else TOPOLOGY
    plan = plan_topology(spec)
    print('Topology: %d switches, %d hosts, %d links, %s' % (
        len(plan['switches']), len(plan['hosts']), len(plan['links']),
        'has loop (STP on)' if plan['cyclic'] else 'loop-free (STP off)'))
    if args.check:
        return
    from mininet.log import setLogLevel
    setLogLevel('info')
    build(spec)


if __name__ == '__main__':
    main()
