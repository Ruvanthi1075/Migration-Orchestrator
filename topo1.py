#!/usr/bin/env python3
"""
topo.py - Quantum-Safe SDN Control-Plane Migration Orchestrator
Mininet emulated data plane. THIS IS THE ONLY FILE YOU EDIT TO CHANGE THE TOPOLOGY.

Everything else adapts on its own:
  * topology.py / coverage.py / optimizer / monitor : live LLDP discovery, no hardcoding
  * flows_config.json, docs/PORTS.md, port registry, Hybrid certs :
        regenerated by ../sync_topology.sh, which this script runs automatically
        after the switches are up (disable with QSMO_AUTO_SYNC=0)
  * live tests : size taken from the OVS bridge count (QSMO_EXPECTED_SWITCHES to override)

HOW TO CHANGE THE TOPOLOGY
--------------------------
Option 1 - edit the line  TOPOLOGY = default_three_tier()  below, e.g.
        TOPOLOGY = ring(6)            TOPOLOGY = tree(depth=3, fanout=2)
        TOPOLOGY = line(5)            TOPOLOGY = star(8)      TOPOLOGY = mesh(4)
Option 2 - no edit:   sudo python3 network/topo.py --topology ring:6
        (default | line:N | ring:N | star:N | mesh:N | tree:DEPTH:FANOUT)
Option 3 - write your own: return/define a dict with the three keys
        {"switches": {name: dpid}, "hosts": {host: switch}, "links": [(sw, sw), ...]}

Rules (validated before Mininet starts):
  * switch names are Mininet-style (s0, s1, ...), dpids are explicit, unique, NON-ZERO
    16-hex strings (OVS treats an all-zero dpid as unset and invents a random one)
  * the switch graph must be connected, hosts must attach to existing switches
  * if the switch graph has a loop, STP is enabled and we wait for it to converge;
    loop-free topologies skip STP and start in seconds

WHY SSL HERE, AND WHY IT'S "LEGACY" NOT "HYBRID" YET
------------------------------------------------------
Every switch's OpenFlow control channel is brought up over TLS using CLASSICAL
certificates (gen_certs.sh). That is the real "Legacy" state migrate_link.py
migrates OUT of. Real Hybrid TLS is added per link by migrate_link.py via stunnel.

IMPORTANT - run migration/gen_certs.sh BEFORE this script. It expects:
    migration/certs/ca.cert, switch.key, switch.cert  (shared by all switches)
"""

import argparse
import os
import subprocess
import sys
import time

_HERE = os.path.dirname(os.path.abspath(__file__))
CERT_DIR = os.path.join(_HERE, '..', 'migration', 'certs')
CA_CERT = os.path.join(CERT_DIR, 'ca.cert')
SWITCH_KEY = os.path.join(CERT_DIR, 'switch.key')
SWITCH_CERT = os.path.join(CERT_DIR, 'switch.cert')
SYNC_SCRIPT = os.path.join(_HERE, '..', 'sync_topology.sh')

CONTROLLER_IP = '127.0.0.1'
CONTROLLER_PORT = 6653

STP_WAIT_S = int(os.environ.get('QSMO_STP_WAIT', '45'))


# ======================================================================
# Topology generators. Each returns {"switches", "hosts", "links"}.
# ======================================================================

def _dpid(i):
    return '%016x' % i


def default_three_tier():
    """The original 7-switch testbed: core s0, agg s1/s2 (cross-linked), 4 edge switches."""
    return {
        'switches': {
            's0': '0000000000000010',  # core (explicit non-zero; see rules above)
            's1': '0000000000000001',  # agg-A
            's2': '0000000000000002',  # agg-B
            's3': '0000000000000003',  # edge
            's4': '0000000000000004',  # edge
            's5': '0000000000000005',  # edge
            's6': '0000000000000006',  # edge
        },
        'hosts': {'h1': 's3', 'h2': 's3', 'h3': 's4', 'h4': 's4',
                  'h5': 's5', 'h6': 's5', 'h7': 's6', 'h8': 's6'},
        'links': [('s3', 's1'), ('s4', 's1'), ('s5', 's2'), ('s6', 's2'),
                  ('s1', 's0'), ('s2', 's0'), ('s1', 's2')],
    }


def _attach_hosts(switch_names, hosts_per_switch, hosts=None):
    hosts = {} if hosts is None else hosts
    for sw in switch_names:
        for _ in range(hosts_per_switch):
            hosts['h%d' % (len(hosts) + 1)] = sw
    return hosts


def _named(n):
    names = ['s%d' % i for i in range(n)]
    return names, {nm: _dpid(i + 1) for i, nm in enumerate(names)}


def line(n, hosts_per_switch=1):
    names, sw = _named(n)
    return {'switches': sw, 'hosts': _attach_hosts(names, hosts_per_switch),
            'links': [(names[i], names[i + 1]) for i in range(n - 1)]}


def ring(n, hosts_per_switch=1):
    names, sw = _named(n)
    links = [(names[i], names[i + 1]) for i in range(n - 1)]
    if n > 2:
        links.append((names[-1], names[0]))
    return {'switches': sw, 'hosts': _attach_hosts(names, hosts_per_switch), 'links': links}


def star(n, hosts_per_leaf=1):
    """Hub s0 plus n leaf switches (n+1 switches total)."""
    names, sw = _named(n + 1)
    return {'switches': sw, 'hosts': _attach_hosts(names[1:], hosts_per_leaf),
            'links': [(names[0], nm) for nm in names[1:]]}


def mesh(n, hosts_per_switch=1):
    names, sw = _named(n)
    return {'switches': sw, 'hosts': _attach_hosts(names, hosts_per_switch),
            'links': [(names[i], names[j]) for i in range(n) for j in range(i + 1, n)]}


def tree(depth, fanout, hosts_per_leaf=1):
    """Complete tree: depth levels below the root, `fanout` children each."""
    links, level, count = [], [0], 1
    for _ in range(depth):
        nxt = []
        for parent in level:
            for _ in range(fanout):
                links.append(('s%d' % parent, 's%d' % count))
                nxt.append(count)
                count += 1
        level = nxt
    names, sw = _named(count)
    return {'switches': sw, 'hosts': _attach_hosts(['s%d' % i for i in level], hosts_per_leaf),
            'links': links}


def from_name(spec):
    """'ring:6' / 'tree:3:2' / 'default' -> topology dict."""
    kind, *args = spec.strip().lower().split(':')
    nums = [int(a) for a in args]
    makers = {'default': default_three_tier, 'line': line, 'ring': ring,
              'star': star, 'mesh': mesh, 'tree': tree}
    if kind not in makers:
        raise SystemExit("unknown topology %r (use default|line:N|ring:N|star:N|mesh:N|tree:D:F)" % spec)
    return makers[kind](*nums)


